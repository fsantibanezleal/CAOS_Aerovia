// Generates src/lib/contract.gen.ts from the schema files of ../docs/contracts/schemas/ (ADR-0080 decision 2: the schema
// files are the single source of every contract; the TypeScript types are generated, never hand-written).
// `--check` generates in memory and fails when the committed file differs, so a schema change without a
// regeneration stops `npm run build` (the currency check; no CI job of its own, ADR-0074).
//
// Aerovia has no HTTP API, so there is no OpenAPI document to start from: the generator's input is the schema files
// themselves, assembled into an OpenAPI 3.1 document with no paths, one component per schema file (named by DOCUMENTS
// below). A schema file that is not in DOCUMENTS fails the generation, so a new schema cannot be left without a type.
// Each file keeps its shared definitions in `$defs`, as a self-contained JSON Schema must; openapi-typescript would
// render `$defs` as a property of every document type, so the files are inlined first: every `$defs` entry becomes a
// component and its references point at it, a reference into another schema file (`network.schema.json#/$defs/options`)
// included. A name defined in several files must be defined identically to be one shared type; a name the files define
// differently keeps the plain name in the files that share the most common definition and is renamed to
// `<Component><Name>` in each of the others, so every file keeps its own definition.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import { register } from 'node:module';

// openapi-typescript renders its output through the TypeScript 5 compiler API (`ts.factory`), which the native
// TypeScript 7 of this product (`typescript`, the type check) does not have. The generator therefore loads the
// TypeScript 5.9.3 kept for it under the name `zz-typescript5` (a name that sorts after `typescript`, so that `tsc`
// stays the native compiler); package.json overrides the package's peer dependency to the root `typescript` so that
// `npm ci` resolves. The hook below points the import of `typescript` made by openapi-typescript, and only by it,
// at that copy.
register(
  'data:text/javascript,' +
    encodeURIComponent(`export async function resolve(specifier, context, next) {
  if (specifier === 'typescript' && /[\/]openapi-typescript[\/]/.test(context.parentURL ?? '')) return next('zz-typescript5', context);
  return next(specifier, context);
}`),
);
const { default: openapiTS, astToString } = await import('openapi-typescript');

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, '..', '..', 'docs', 'contracts');
const target = join(here, '..', 'src', 'lib', 'contract.gen.ts');
const HEADER = '// GENERATED by frontend/scripts/gen-contract-types.mjs from docs/contracts/schemas/. Do not edit.\n';

/** The component name each schema file generates (the file name without `.schema.json`). */
export const DOCUMENTS = {
  'artifact-manifest': 'ArtifactManifest',
  'branch-table': 'BranchTableRow',
  'browser-evidence': 'BrowserEvidence',
  catalog: 'Catalog',
  checkpoint: 'Checkpoint',
  'engine-worker': 'EngineWorker',
  'model-io': 'ModelIo',
  'model-manifest': 'ModelManifest',
  'model-registry': 'ModelRegistry',
  network: 'NetworkLibrary',
  'onnx-parity': 'OnnxParity',
  project: 'ProjectFile',
  readiness: 'Readiness',
  'reference-checks': 'ReferenceChecks',
  'release-identity': 'ReleaseIdentity',
  science: 'Science',
  transport: 'Transport',
};

const readJSON = (path) => JSON.parse(readFileSync(path, 'utf8'));
const schemaFile = (name) => join(contracts, 'schemas', `${name}.schema.json`);

/**
 * A copy of `node` where every reference is a local one: `#/$defs/<name>` becomes the component of that definition
 * in `file` (renamed when the files define the name differently), and `<other>.schema.json#/$defs/<name>` the
 * component of that definition in the other file. A reference to a whole schema file is not used by the catalog and
 * fails.
 */
function relink(node, file, files, from) {
  if (Array.isArray(node)) return node.map((n) => relink(n, file, files, from));
  if (node === null || typeof node !== 'object') return node;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if (key !== '$ref' || typeof value !== 'string') {
      out[key] = relink(value, file, files, from);
      continue;
    }
    const [path, frag = ''] = value.split('#');
    const owner = path === '' ? file : files.get(posix.basename(path).replace(/\.schema\.json$/, ''));
    if (!owner || !frag.startsWith('/$defs/')) throw new Error(`${from}: cannot link ${value}`);
    const defName = frag.slice('/$defs/'.length);
    if (!(defName in owner.defs)) throw new Error(`${from}: ${value} names no definition`);
    out[key] = `#/components/schemas/${owner.rename[defName] ?? defName}`;
  }
  return out;
}

/**
 * A copy of `node` where the length bounds of an array are dropped unless the array is a pair (minItems = maxItems = 2:
 * a bound or a range). openapi-typescript's `arrayLength` then types a pair as `[number, number]`, as the reader needs
 * it, and every other array, a vector indexed by a number or a list that may be long, as `T[]`; a vector typed as a
 * tuple, or `minItems: 1` as `[T, ...T[]]`, only gets in the way of indexing it in a loop. An array with `prefixItems` is
 * already a tuple of its positions: with the bounds as well, openapi-typescript nests the tuple in every position.
 */
function pairsOnly(node) {
  if (Array.isArray(node)) return node.map(pairsOnly);
  if (node === null || typeof node !== 'object') return node;
  const pair = node.minItems === 2 && node.maxItems === 2 && node.prefixItems === undefined;
  const out = {};
  for (const [key, value] of Object.entries(node)) {
    if ((key === 'minItems' || key === 'maxItems') && !pair) continue;
    out[key] = pairsOnly(value);
  }
  return out;
}

/** The component name `<Component><Name>` a definition takes when files define `name` differently. */
const qualified = (component, name) => `${component}${name[0].toUpperCase()}${name.slice(1)}`;

/** The OpenAPI document with every schema file as a component and every `$defs` hoisted. */
export function inlineDocument() {
  const present = readdirSync(join(contracts, 'schemas'))
    .filter((f) => f.endsWith('.schema.json'))
    .map((f) => f.replace(/\.schema\.json$/, ''));
  for (const name of present) if (!(name in DOCUMENTS)) throw new Error(`schema ${name} has no entry in DOCUMENTS`);
  for (const name of Object.keys(DOCUMENTS)) if (!present.includes(name)) throw new Error(`DOCUMENTS names ${name}, which has no schema file`);
  const files = new Map();
  const taken = new Set(Object.values(DOCUMENTS));
  for (const [name, component] of Object.entries(DOCUMENTS)) {
    const { $defs = {}, $schema: _dialect, $id: _id, ...body } = readJSON(schemaFile(name));
    for (const defName of Object.keys($defs)) {
      if (taken.has(defName)) throw new Error(`$defs ${defName} of ${name} collides with a component`);
    }
    files.set(name, { name, component, defs: $defs, body, rename: {} });
  }
  // A name is shared while every file that defines it defines it identically once its own references are linked; a
  // renamed definition can change what another definition means, so the comparison repeats until nothing changes.
  for (let changed = true; changed; ) {
    changed = false;
    const seen = {};
    for (const f of files.values()) {
      for (const [defName, def] of Object.entries(f.defs)) {
        if (defName in f.rename) continue;
        (seen[defName] ??= []).push({ f, defName, text: JSON.stringify(relink(def, f, files, `${f.name}#/$defs/${defName}`)) });
      }
    }
    for (const uses of Object.values(seen)) {
      const counts = new Map();
      for (const { text } of uses) counts.set(text, (counts.get(text) ?? 0) + 1);
      if (counts.size > 1) {
        // the definition most files share (the first on a tie) keeps the plain name; each other file's is renamed
        const keeper = [...counts.entries()].reduce((best, e) => (e[1] > best[1] ? e : best))[0];
        for (const { f, defName, text } of uses) if (text !== keeper) f.rename[defName] = qualified(f.component, defName);
        changed = true;
      }
    }
  }
  const schemas = {};
  for (const f of files.values()) {
    for (const [defName, def] of Object.entries(f.defs)) {
      const name = f.rename[defName] ?? defName;
      if (taken.has(name)) throw new Error(`$defs ${defName} of ${f.name} collides with a component`);
      schemas[name] = relink(def, f, files, `${f.name}#/$defs/${defName}`);
    }
    schemas[f.component] = relink(f.body, f, files, f.name);
  }
  return { openapi: '3.1.0', info: { title: 'Aerovia contracts', version: '1.0.0' }, paths: {}, components: { schemas } };
}

const ast = await openapiTS(pairsOnly(inlineDocument()), { arrayLength: true });
const body = astToString(ast).replace(/\r\n/g, '\n').replace(/\s+$/, '');
const text = `${HEADER}${body}\n`;

if (process.argv.includes('--check')) {
  let current = null;
  try {
    current = readFileSync(target);
  } catch {
    // an absent file is not current
  }
  if (current === null || !current.equals(Buffer.from(text, 'utf8'))) {
    console.error('contract.gen.ts is not current: run npm run contracts:types');
    process.exit(1);
  }
  console.log('contract types: current');
} else {
  writeFileSync(target, text, 'utf8');
  console.log('contract types: wrote frontend/src/lib/contract.gen.ts');
}
